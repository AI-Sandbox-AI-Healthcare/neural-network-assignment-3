# The worked toy example — the SAME 2-patient / 3-visit table shown in the UI
# Explorer's Sequence Explorer tab. Feature column order is FEATURE_COLS.
#
#   patient A : 3 visits   patient B : 2 visits    max_len = 3
#
#   padded A = [[ 0, 2, 1, 1],   padded B = [[ 0, 1, 0, 1],
#               [30, 5, 2, 2],               [14, 4, 1, 5],
#               [61, 7, 3, 3]]               [ 0, 0, 0, 0]]   <- padding
#
#   lengths = [3, 2]      mask = [[1,1,1],
#                                 [1,1,0]]
# ---------------------------------------------------------------------------
TOY_ROWS = [
    # deliberately out of visit_number order, to test the sort
    ("A", 3, 61, 7.0, 3, 3),
    ("A", 1, 0, 2.0, 1, 1),
    ("A", 2, 30, 5.0, 2, 2),
    ("B", 2, 14, 4.0, 1, 5),
    ("B", 1, 0, 1.0, 0, 1),
]
TOY_DF = pd.DataFrame(TOY_ROWS, columns=[
    "patient_id", "visit_number", *FEATURE_COLS,
])
TOY_A = np.array([[0, 2, 1, 1], [30, 5, 2, 2], [61, 7, 3, 3]], dtype=float)
TOY_B_PADDED = np.array([[0, 1, 0, 1], [14, 4, 1, 5], [0, 0, 0, 0]], dtype=float)


