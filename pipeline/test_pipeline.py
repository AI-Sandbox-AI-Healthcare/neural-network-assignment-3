def _rnn_module(model):
    """The lone nn.LSTM / nn.GRU inside a model, whichever is present."""
    import torch
    rnns = [m for m in model.modules() if isinstance(m, (torch.nn.LSTM, torch.nn.GRU))]
    assert len(rnns) == 1, "the model must contain exactly one LSTM or GRU layer"
    return rnns[0]


@pytest.mark.timeout(120)
def test_build_sequence_classifier_lstm_structure_and_forward():
    torch = pytest.importorskip("torch")
    nn = torch.nn

    model = _impl(pipeline.build_sequence_classifier, (6, 4), "lstm", 16, False)
    assert isinstance(model, nn.Module)

    rnn = _rnn_module(model)
    assert isinstance(rnn, nn.LSTM)
    assert rnn.input_size == 4 and rnn.hidden_size == 16
    assert rnn.batch_first is True
    assert rnn.bidirectional is False

    linears = [m for m in model.modules() if isinstance(m, nn.Linear)]
    assert linears[-1].out_features == 1
    assert linears[-1].in_features == 16                    # hidden_units * 1 direction
    assert any(isinstance(m, nn.Sigmoid) for m in model.modules())

    model.eval()
    with torch.no_grad():
        probs = model(torch.zeros(5, 6, 4))
    assert tuple(probs.shape) == (5, 1)
    assert bool((probs >= 0).all() and (probs <= 1).all())

    # masking: a batch that is all padding must not blow up (no div-by-zero)
    with torch.no_grad():
        z = model(torch.zeros(3, 6, 4))
    assert torch.isfinite(z).all()


@pytest.mark.timeout(120)
def test_build_sequence_classifier_gru_and_bidirectional():
    torch = pytest.importorskip("torch")
    nn = torch.nn

    gru = _impl(pipeline.build_sequence_classifier, (4, 4), "gru", 8, False)
    assert isinstance(_rnn_module(gru), nn.GRU)

    bi = _impl(pipeline.build_sequence_classifier, (4, 4), "lstm", 8, True)
    bi_rnn = _rnn_module(bi)
    assert bi_rnn.bidirectional is True
    bi_linears = [m for m in bi.modules() if isinstance(m, nn.Linear)]
    assert bi_linears[-1].in_features == 16                 # hidden_units * 2 directions
    bi.eval()
    with torch.no_grad():
        assert tuple(bi(torch.zeros(2, 4, 4)).shape) == (2, 1)

    with pytest.raises(ValueError):
        pipeline.build_sequence_classifier((4, 4), "rnn", 8, False)


